#!/usr/bin/env python3
"""Build GitHub Releases latest.json from the already-signed Tauri update assets.

Does not sign anything. Requires the matching .sig generated by Tauri using
the owner's private signing key, which must never be committed or logged.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

PLATFORMS=("darwin-aarch64","windows-x86_64","linux-x86_64")


def manifest(version:str, assets:dict[str,tuple[Path,Path]]) -> dict:
    if not version or any(c not in "0123456789." for c in version) or len(version.split("."))!=3:
        raise ValueError("Version must use X.Y.Z")
    if set(assets)!=set(PLATFORMS):
        raise ValueError("All three signed desktop platforms are required")
    entries={}
    for target,(artifact,signature) in assets.items():
        if not artifact.is_file() or artifact.stat().st_size<1024:
            raise ValueError(f"Missing binary update for {target}")
        if not signature.is_file():
            raise ValueError(f"Missing Tauri .sig for {target}")
        raw=signature.read_text().strip()
        if not raw or len(raw)>8192:
            raise ValueError(f"Invalid .sig for {target}")
        entries[target]={
            "signature":raw,
            "url":f"https://github.com/blarkin13/humperdinck/releases/download/desktop-v{version}/{artifact.name}"
        }
    return {"version":version,
            "notes":"Humperdinck desktop release for Windows, macOS and Linux",
            "platforms":entries}


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--version",required=True)
    p.add_argument("--output",type=Path,default=Path("latest.json"))
    for target in PLATFORMS:
        name=target.replace("-","_")
        p.add_argument("--"+name+"-asset",required=True,type=Path)
        p.add_argument("--"+name+"-signature",required=True,type=Path)
    args=p.parse_args()
    assets={}
    for target in PLATFORMS:
        name=target.replace("-","_")
        assets[target]=(getattr(args,name+"_asset"),getattr(args,name+"_signature"))
    result=manifest(args.version,assets)
    args.output.write_text(json.dumps(result,indent=2)+"\n")
    print("Wrote signed update manifest for "+args.version)


if __name__=="__main__":
    main()
